/*
 * 把 char* 中的双字节汉字码解成字形索引并绘制
 * draw 由调用方提供: 绘制单个 14x15 点阵
 */

/* 解码: 高位字节 = 0x80|(idx>>7), 低位字节 = 0x20|(idx&0x7F)
 * 低位刻意避开 0x00/0x08/0x09/0x0A, 否则会被当成 NUL/退格/换行 */
uint16_t cjk_next(const char **pp)
{
  const char *p = *pp;
  if (!p || !(uint8_t)*p) return 0xFFFF;
  if ((uint8_t)*p & 0x80) {
    uint16_t idx = ((uint16_t)((uint8_t)p[0] & 0x7F) << 7) | ((uint8_t)p[1] - 0x20);
    *pp = p + 2;
    return idx < CJK_COUNT ? idx : 0;
  }
  return 0xFFFF;
}
